"""Synchronize docs/presentation/evidence.json with the captured assets.

The presentation deck, PDF, and screenshot set are regenerated by
``scripts/capture_demo.py``. This tool rewrites the machine-readable evidence
index so a reviewer can verify every committed asset hash without trusting a
manual copy/paste step.
"""

from __future__ import annotations

import hashlib
import json
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PRESENTATION = ROOT / "docs" / "presentation"
EVIDENCE = PRESENTATION / "evidence.json"
ASSETS = PRESENTATION / "assets"


def sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def main() -> int:
    payload = json.loads(EVIDENCE.read_text(encoding="utf-8"))
    old_assets = {item["file"]: item for item in payload.get("assets", [])}
    files = sorted(p for p in ASSETS.glob("*.png") if p.is_file())
    assets = []
    for path in files:
        rel = path.relative_to(PRESENTATION).as_posix()
        assets.append({
            "file": rel,
            "bytes": path.stat().st_size,
            "sha256": sha256(path),
        })
    payload["assets"] = assets
    payload["asset_count"] = len(assets)

    manifest_path = ASSETS / "capture-manifest.json"
    if manifest_path.is_file():
        manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
        after = manifest.get("after_decision", {})
        facts = manifest.get("content_facts", {})
        run = payload.setdefault("run", {})
        if after:
            run["packet_hash_after_actions"] = after.get("packet_hash", run.get("packet_hash_after_actions"))
            run["audit_head_after_actions"] = after.get("audit_head", run.get("audit_head_after_actions"))
            run["audit_events_after_actions"] = after.get("audit_events", run.get("audit_events_after_actions"))
            run["assumptions_after_actions"] = after.get("assumptions", run.get("assumptions_after_actions"))
        if facts:
            run["snapshot_short"] = facts.get("snapshot_short", run.get("snapshot_short"))
            run["snapshot_hash"] = facts.get("snapshot_hash", run.get("snapshot_hash"))
            run["packet_hash_seed"] = facts.get("packet_cover_packet", run.get("packet_hash_seed"))
            run["packet_cover_snapshot"] = facts.get("packet_cover_snapshot", run.get("packet_cover_snapshot"))
        run_id = payload.get("run", {}).get("run_id") or manifest.get("run_id", "R-DEMO-001")
        live_packet = ROOT / "data" / "runs" / run_id / "packet.json"
        if live_packet.is_file():
            live = json.loads(live_packet.read_text(encoding="utf-8"))
            run["packet_hash_predecision"] = live.get("packet_sha256", run.get("packet_hash_predecision"))
            run["audit_head_predecision"] = live.get("audit_head", run.get("audit_head_predecision"))
            run["audit_events_predecision"] = live.get("audit_event_count", run.get("audit_events_predecision"))
        if facts.get("packet_cover_packet"):
            run["packet_hash_predecision"] = facts["packet_cover_packet"]
        run["packet_hash_seed"] = run.get("packet_hash_predecision", run.get("packet_hash_seed"))
        failures = manifest.get("crop_failures", [])
        payload.setdefault("validation", {})["crop_failures"] = len(failures)
        payload["validation"]["capture_ok"] = not failures
    pdf = PRESENTATION / "PreFlight-deck.pdf"
    if pdf.is_file():
        validation_path = ASSETS / "deck-validation.json"
        validation = json.loads(validation_path.read_text(encoding="utf-8")) if validation_path.is_file() else {}
        deck = payload.setdefault("deck", {})
        deck["pdf_sha256"] = sha256(pdf)
        deck["pdf_bytes"] = pdf.stat().st_size
        deck["pdf_pages"] = 16
        deck["pdf_page_size"] = validation.get("pdf", {}).get("page_size", deck.get("pdf_page_size", "1200 x 675.12 pts"))
        # The validation file is written before the PDF render; refresh its PDF block too.
        pdf_validation = validation.setdefault("pdf", {})
        pdf_validation.update({
            "pdf": "docs/presentation/PreFlight-deck.pdf",
            "bytes": pdf.stat().st_size,
            "sha256": sha256(pdf),
            "pages": deck["pdf_pages"],
            "page_size": deck["pdf_page_size"],
        })
        (ASSETS / "deck-validation.json").write_text(json.dumps(validation, indent=2) + "\n", encoding="utf-8")
        payload.setdefault("validation", {})["pdf"] = pdf_validation
        failures = sum(
            len(viewport.get("failures", []))
            for viewport in validation.get("deck_validation", {}).get("viewports", {}).values()
        )
        deck["validation"] = (
            "Playwright at 1920x1080, 1440x900, 1280x720, 1024x768, 390x844: "
            f"{deck.get('slides', 16)} slides; {failures} viewport overflow failures; "
            "0 console errors; 0 external requests; crop validation enforced by the capture script; "
            f"PDF {deck['pdf_pages']} pages at {deck['pdf_page_size']}"
        )
    payload["generated_at"] = datetime.now(timezone.utc).replace(microsecond=0).isoformat().replace("+00:00", "Z")
    EVIDENCE.write_text(json.dumps(payload, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    print(
        f"updated {EVIDENCE.relative_to(ROOT)}: {len(assets)} assets "
        f"(was {len(old_assets)}), pdf {payload['deck'].get('pdf_sha256', 'n/a')[:12]}..."
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
